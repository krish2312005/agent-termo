import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import type { AgentTranscriptEntry } from './agent-transcript.js';
import { isPathWithinWorkspace } from './workspace.js';

export type AgentRunStatus = 'running' | 'waiting' | 'completed' | 'failed' | 'cancelled';

export interface AgentActivityReportInput {
	agentName: string;
	agentId: string;
	task: string;
	turn: number;
	status: AgentRunStatus;
	startedAt: number;
	endedAt: number;
	detail?: string;
	entries: readonly AgentTranscriptEntry[];
}

function safeSegment(value: string): string {
	return value.toLowerCase().replace(/[^a-z0-9_-]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 48) || 'agent';
}

export function agentWorkReportPath(agentName: string, agentId: string, turn: number): string {
	return 'docs/agent-reports/' + safeSegment(agentName) + '-' + safeSegment(agentId) + '-turn-' + Math.max(1, Math.floor(turn)) + '.md';
}

export function agentActivityReportPath(agentName: string, agentId: string, turn: number): string {
	return 'docs/agent-activity/' + safeSegment(agentName) + '-' + safeSegment(agentId) + '-turn-' + Math.max(1, Math.floor(turn)) + '.md';
}

function redact(value: string): string {
	return value
		.replace(/\b(?:nvapi-[a-z0-9_-]{12,}|sk-[a-z0-9_-]{12,}|gh[pousr]_[a-z0-9_]{20,}|github_pat_[a-z0-9_]{20,})\b/gi, '[REDACTED]')
		.replace(/(\bBearer\s+)[a-z0-9._~+\/=-]+/gi, '$1[REDACTED]')
		.replace(/(\b(?:api[_-]?key|access[_-]?token|refresh[_-]?token|password|secret|authorization)\b\s*[:=]\s*)(["']?)[^\s"',;]+/gi, '$1[REDACTED]')
		.replace(/(--?(?:api[-_]?key|token|password|secret|authorization)\s+)(["']?)[^\s"',;]+/gi, '$1[REDACTED]');
}

function clean(value: string, max = 1_000): string {
	const text = redact(value.replace(/[\r\n]+/g, ' ').replace(/\s+/g, ' ').trim());
	return text.length <= max ? text : text.slice(0, max - 1) + '…';
}

function inlineCode(value: string): string {
	const escaped = clean(value, 240).split(String.fromCharCode(96)).join('\\' + String.fromCharCode(96));
	return String.fromCharCode(96) + escaped + String.fromCharCode(96);
}

/** Persist a redacted execution trace without copying file contents or model reasoning. */
export async function writeAgentActivityReport(
	projectRoot: string,
	input: AgentActivityReportInput,
): Promise<string> {
	const path = agentActivityReportPath(input.agentName, input.agentId, input.turn);
	const fullPath = resolve(projectRoot, path);
	if (!isPathWithinWorkspace(fullPath, projectRoot)) {
		throw new Error('Activity report path is outside the project workspace.');
	}

	const actions = input.entries.filter((entry) => entry.kind === 'tool' && entry.tool);
	const lines = [
		'# Agent activity: ' + clean(input.agentName, 80),
		'',
		'- Generated by Agent-Termo from recorded tool events.',
		'- Agent ID: ' + clean(input.agentId, 80),
		'- Turn: ' + Math.max(1, Math.floor(input.turn)),
		'- Status: ' + input.status,
		'- Started: ' + new Date(input.startedAt).toISOString(),
		'- Finished: ' + new Date(input.endedAt).toISOString(),
		'- Duration: ' + Math.max(0, input.endedAt - input.startedAt) + ' ms',
		'- Task: ' + clean(input.task),
		'',
		'## Recorded tool actions',
		'',
	];

	if (actions.length === 0) {
		lines.push('- No tool calls were recorded during this turn.');
	} else {
		actions.forEach((entry, index) => {
			const tool = entry.tool!;
			const duration = tool.endedAt === undefined ? 'incomplete' : Math.max(0, tool.endedAt - tool.startedAt) + ' ms';
			const args = tool.args ? ' ' + inlineCode(tool.args) : '';
			lines.push((index + 1) + '. **' + clean(tool.name, 80) + '**' + args + ' — ' + tool.state + '; ' + duration);
		});
	}

	if (input.detail) {
		lines.push('', '## Failure details', '', clean(input.detail));
	}

	lines.push('', '> File contents, model reasoning, and raw tool output are intentionally excluded from this activity log.', '');
	await mkdir(dirname(fullPath), { recursive: true });
	await writeFile(fullPath, lines.join('\n'), 'utf8');
	return path;
}
